'use strict';
/*
 * Offline demo: runs demo/leads.json through the REAL generated Code nodes of workflows/leadflow-sales-ai.json
 * using the in-memory simulator in tests/helpers/n8n-sim.js. No n8n, no Google Sheets, no Groq, no network.
 *
 * What is simulated: Google Sheets (an in-memory table) and the language model (canned answers from
 * demo/ai-responses.json). What is real: every Code node, i.e. validation, duplicate arbitration, prompt
 * construction, answer validation, scoring and drafts.
 *
 *   npm run demo:local               print the result as Markdown
 *   npm run demo:local -- --json     print the raw result tables as JSON
 *   npm run demo:local -- --write    rewrite demo/expected-output.md (a test checks that it is up to date)
 */
const fs = require('node:fs');
const path = require('node:path');
const { FakeSheet, sendWebhook } = require('../tests/helpers/n8n-sim.js');

const ROOT = path.join(__dirname, '..');
const NOW = '2026-10-26T09:00:00.000Z';
const minute = (m) => new Date(Date.parse(NOW) + m * 60000).toISOString();
const read = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, f), 'utf8'));

const leads = read('demo/leads.json').map(({ _note, ...payload }) => ({ note: _note, payload }));
const canned = read('demo/ai-responses.json');
const invalid = read('demo/ai-invalid-examples.json');
const hotPayload = leads[0].payload;

const answer = (obj, finish) => ({ choices: [{ message: { role: 'assistant', content: typeof obj === 'string' ? obj : JSON.stringify(obj) }, finish_reason: finish || 'stop' }] });
const responder = (req, lead) => {
  const a = canned[String(lead.email).toLowerCase()];
  return a ? answer(a) : { error: 'no canned answer for this lead' };
};

function buildResult() {
  const sheet = new FakeSheet();
  const round1 = leads.map((l, i) => {
    const r = sendWebhook(sheet, l.payload, { now: minute(i), aiResponder: responder, execId: 'demo-' + (i + 1) });
    const email = String(l.payload.email || '').toLowerCase();
    const row = sheet.tabs.leads.find((x) => String(x.email).toLowerCase() === email);
    const task = row ? sheet.tabs.seguimiento.find((t) => t.submission_id === row.submission_id) : null;
    return {
      lead: l.payload.full_name, note: l.note, http: r.responded.code,
      status: row ? row.status : '(not stored)', priority: row ? row.priority : '', score: row ? row.score : '',
      intent: row ? row.intent : '', flags: row ? row.flags : '', review: row ? row.human_review_required : '',
      task: task ? task.task_type + ' / ' + task.status : 'none'
    };
  });
  const before = { leads: sheet.tabs.leads.length, tasks: sheet.tabs.seguimiento.length };
  const round2 = leads.map((l, i) => {
    const r = sendWebhook(sheet, l.payload, { now: minute(20 + i), aiResponder: responder, execId: 'demo-again-' + (i + 1) });
    return { lead: l.payload.full_name, http: r.responded.code, body: JSON.stringify(r.responded.body) };
  });
  const after = { leads: sheet.tabs.leads.length, tasks: sheet.tabs.seguimiento.length };

  const badAi = invalid.map((c, i) => {
    const s = new FakeSheet();
    const content = c.object ? c.object : c.content;
    sendWebhook(s, hotPayload, { now: minute(i), aiResponder: () => answer(content, c.finish_reason) });
    const row = s.tabs.leads[0];
    return {
      case: c.case, status: row.status, priority: row.priority || '(none)', review: row.human_review_required,
      flags: row.flags || '', task: s.tabs.seguimiento.length ? 'created' : 'none', error: s.tabs.errores.length ? s.tabs.errores[0].message : ''
    };
  });
  return { round1, round2, counts: { before, after }, badAi, rows: { leads: sheet.tabs.leads.length, tasks: sheet.tabs.seguimiento.length, errors: sheet.tabs.errores.length, claims: sheet.tabs.claims.length } };
}

const esc = (s) => String(s === undefined || s === null || s === '' ? ' ' : s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (head, rows) => ['| ' + head.join(' | ') + ' |', '| ' + head.map(() => '---').join(' | ') + ' |'].concat(rows.map((r) => '| ' + r.map(esc).join(' | ') + ' |')).join('\n');

function markdown(res) {
  const out = [];
  out.push('# Expected output of `npm run demo:local`');
  out.push('');
  out.push('> **Simulated run.** The real generated Code nodes of the workflow process the seven fictional leads of [`leads.json`](leads.json). Google Sheets is an in-memory table and the language model is replaced by the canned answers in [`ai-responses.json`](ai-responses.json). This file is regenerated by `npm run demo:local -- --write`, and a test fails if it is out of date. Results on the live stack depend on what the real model extracts; see [docs/TEST_REPORT.md](../docs/TEST_REPORT.md).');
  out.push('');
  out.push('## Round 1: seven new leads');
  out.push('');
  out.push(table(['Lead', 'HTTP', 'Status', 'Priority', 'Score', 'Intent', 'Review', 'Flags', 'Follow-up task'], res.round1.map((r) => [r.lead, r.http, r.status, r.priority, r.score, r.intent, r.review, r.flags, r.task])));
  out.push('');
  out.push('## Round 2: the same seven leads again');
  out.push('');
  out.push(table(['Lead', 'HTTP', 'Answer'], res.round2.map((r) => [r.lead, r.http, '`' + r.body + '`'])));
  out.push('');
  out.push('Rows before the second round: ' + res.counts.before.leads + ' leads, ' + res.counts.before.tasks + ' tasks. After: ' + res.counts.after.leads + ' leads, ' + res.counts.after.tasks + ' tasks. Duplicates add nothing.');
  out.push('');
  out.push('## Model answers that must not be trusted');
  out.push('');
  out.push('The hot lead (Marta Sanz) is processed again, each time with a different broken or hostile answer from [`ai-invalid-examples.json`](ai-invalid-examples.json):');
  out.push('');
  out.push(table(['Case', 'Lead status', 'Priority', 'Review', 'Flags', 'Task', 'Logged error'], res.badAi.map((r) => [r.case, r.status, r.priority, r.review, r.flags, r.task, r.error])));
  out.push('');
  out.push('## Why each lead ends where it does');
  out.push('');
  out.push(table(['Lead', 'Scenario'], res.round1.map((r) => [r.lead, r.note])));
  out.push('');
  return out.join('\n');
}

if (require.main === module) {
  const res = buildResult();
  if (process.argv.includes('--json')) {
    console.log(JSON.stringify(res, null, 2));
  } else if (process.argv.includes('--write')) {
    fs.writeFileSync(path.join(ROOT, 'demo/expected-output.md'), markdown(res) + '\n');
    console.log('wrote demo/expected-output.md');
  } else {
    console.log(markdown(res));
  }
}

module.exports = { buildResult, markdown };
