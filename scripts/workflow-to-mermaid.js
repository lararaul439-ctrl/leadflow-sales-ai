'use strict';
/*
 * Draws the graph of the committed n8n export (workflows/leadflow-sales-ai.json) as a Mermaid flowchart.
 *
 *   node scripts/workflow-to-mermaid.js          rewrite docs/diagrams/workflow-overview.mmd
 *   node scripts/workflow-to-mermaid.js --check  fail if the committed .mmd is out of date (used by a test)
 *
 * The picture is GENERATED FROM THE EXPORT FILE. It is not a screenshot of the n8n editor.
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const EXPORT = path.join(ROOT, 'workflows/leadflow-sales-ai.json');
const TARGET = path.join(ROOT, 'docs/diagrams/workflow-overview.mmd');

const CLASS_BY_TYPE = {
  'n8n-nodes-base.webhook': 'trigger',
  'n8n-nodes-base.manualTrigger': 'trigger',
  'n8n-nodes-base.set': 'cfg',
  'n8n-nodes-base.if': 'branch',
  'n8n-nodes-base.code': 'code',
  'n8n-nodes-base.respondToWebhook': 'respond',
  'n8n-nodes-base.googleSheets': 'sheets',
  'n8n-nodes-base.httpRequest': 'http'
};

function build(workflow) {
  const nodes = workflow.nodes.filter((n) => n.type !== 'n8n-nodes-base.stickyNote');
  const id = new Map(nodes.map((n, i) => [n.name, 'n' + (i + 1)]));
  const label = (n) => n.name.replace(/"/g, "'");
  const lines = [];
  lines.push('%% Generated by scripts/workflow-to-mermaid.js from workflows/leadflow-sales-ai.json. Do not edit by hand.');
  lines.push('flowchart TB');
  lines.push('  classDef trigger fill:#fef2f2,stroke:#dc2626,color:#7f1d1d');
  lines.push('  classDef cfg fill:#f1f5f9,stroke:#64748b,color:#0f172a');
  lines.push('  classDef branch fill:#fefce8,stroke:#ca8a04,color:#713f12');
  lines.push('  classDef code fill:#ecfdf5,stroke:#059669,color:#064e3b');
  lines.push('  classDef respond fill:#eef2ff,stroke:#4f46e5,color:#1e1b4b');
  lines.push('  classDef sheets fill:#fff7ed,stroke:#ea580c,color:#7c2d12');
  lines.push('  classDef http fill:#f5f3ff,stroke:#7c3aed,color:#3b0764');
  nodes.forEach((n) => {
    const shape = n.type === 'n8n-nodes-base.if' ? ['{"', '"}'] : n.type === 'n8n-nodes-base.googleSheets' ? ['[("', '")]'] : ['["', '"]'];
    lines.push('  ' + id.get(n.name) + shape[0] + label(n) + shape[1] + ':::' + (CLASS_BY_TYPE[n.type] || 'cfg'));
  });
  const edges = [];
  nodes.forEach((n) => {
    const out = (workflow.connections[n.name] || {}).main || [];
    out.forEach((targets, port) => {
      (targets || []).forEach((t) => {
        if (!id.has(t.node)) return;
        const isIf = n.type === 'n8n-nodes-base.if';
        const tag = isIf ? (port === 0 ? '|true|' : '|false|') : '';
        edges.push('  ' + id.get(n.name) + ' -->' + tag + ' ' + id.get(t.node));
      });
    });
  });
  return lines.concat(edges).join('\n') + '\n';
}

if (require.main === module) {
  const text = build(JSON.parse(fs.readFileSync(EXPORT, 'utf8')));
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    if (current !== text) {
      console.error('docs/diagrams/workflow-overview.mmd is out of date. Run: node scripts/workflow-to-mermaid.js');
      process.exit(1);
    }
    console.log('workflow graph is up to date');
  } else {
    fs.writeFileSync(TARGET, text);
    console.log('wrote docs/diagrams/workflow-overview.mmd');
  }
}

module.exports = { build };
