#!/usr/bin/env node
'use strict';
/*
 * Builds workflows/leadflow-sales-ai.json (importable n8n export) and templates/*.csv
 * from src/lead-core.js (business logic) and src/nodes/*.js (Code node glue).
 *   node scripts/build-workflow.js          write the files
 *   node scripts/build-workflow.js --check  fail if the committed files are out of date
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const core = require('../src/lead-core.js');

const ROOT = path.join(__dirname, '..');
const { CONFIG, COLUMNS } = core;

// ------------------------------------------------------------------ code embedding
function parseRegions(source) {
  const regions = {};
  const lines = source.split('\n');
  let cur = null;
  for (const line of lines) {
    const start = line.match(/^\/\/#region\s+(\w+)(?:\s*::\s*(.*))?$/);
    if (start) {
      cur = { name: start[1], deps: start[2] ? start[2].split(',').map((s) => s.trim()).filter(Boolean) : [], body: [] };
      continue;
    }
    if (line.startsWith('//#endregion')) { regions[cur.name] = cur; cur = null; continue; }
    if (cur) cur.body.push(line);
  }
  return regions;
}

function resolveOrder(regions, roots) {
  const order = [];
  const seen = new Set();
  const visit = (n) => {
    if (seen.has(n)) return;
    if (!regions[n]) throw new Error('Unknown region: ' + n);
    seen.add(n);
    regions[n].deps.forEach(visit);
    order.push(n);
  };
  roots.forEach(visit);
  return order;
}

function buildCode(glueFile) {
  const regions = parseRegions(fs.readFileSync(path.join(ROOT, 'src/lead-core.js'), 'utf8'));
  const glue = fs.readFileSync(path.join(ROOT, 'src/nodes', glueFile), 'utf8');
  const uses = (glue.match(/^\/\/#uses\s+(.*)$/m) || [, ''])[1].split(',').map((s) => s.trim()).filter(Boolean);
  const order = resolveOrder(regions, uses);
  const libs = order.map((n) => regions[n].body.join('\n').trim()).join('\n\n');
  const glueBody = glue.replace(/^\/\/#uses.*\n/m, '').trim();
  const compact = (txt) => txt.split('\n').filter((l) => l.trim() !== '' && !/^\s*\/\//.test(l)).join('\n');
  return '// LeadFlow Sales AI v' + CONFIG.version + ' - generated by scripts/build-workflow.js from src/. Do not edit here.\n' +
    compact(libs) + '\n// ---- node logic ----\n' + compact(glueBody) + '\n';
}

// ------------------------------------------------------------------ node helpers
const uid = (name) => {
  const h = crypto.createHash('sha256').update('leadflow-sales-ai|' + name).digest('hex');
  return h.slice(0, 8) + '-' + h.slice(8, 12) + '-4' + h.slice(13, 16) + '-a' + h.slice(17, 20) + '-' + h.slice(20, 32);
};

const SHEET_ID_EXPR = '={{ $("Configuración").first().json.sheet_id }}';
const docRef = () => ({ __rl: true, mode: 'id', value: SHEET_ID_EXPR });
const tabRef = (name) => ({ __rl: true, mode: 'name', value: name });
const SHEETS_CRED = { googleSheetsOAuth2Api: { id: 'REPLACE_WITH_YOUR_CREDENTIAL', name: 'Google Sheets account' } };

function mappingFor(columns, ref, keys) {
  const value = {};
  columns.forEach((c) => { value[c] = '={{ ' + ref + '.' + c + ' }}'; });
  return {
    mappingMode: 'defineBelow',
    value,
    matchingColumns: keys,
    schema: [],
    attemptToConvertTypes: false,
    convertFieldsToString: false
  };
}

function upsertNode(name, tab, columns, ref, key, position, notes) {
  return {
    name, type: 'n8n-nodes-base.googleSheets', typeVersion: 4.7, position, notes,
    parameters: {
      resource: 'sheet', operation: 'appendOrUpdate', documentId: docRef(), sheetName: tabRef(tab),
      columns: mappingFor(columns, ref, [key]),
      options: { cellFormat: 'RAW' }
    },
    credentials: SHEETS_CRED
  };
}

const cond = (left, op, right) => ({
  options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 },
  conditions: [Object.assign({ id: uid('c|' + left + op + right).slice(0, 18), leftValue: left, operator: op }, right === undefined ? {} : { rightValue: right })],
  combinator: 'and'
});
const ifNode = (name, conditions, position) => ({ name, type: 'n8n-nodes-base.if', typeVersion: 2.4, position, parameters: { conditions, options: {} } });
const codeNode = (name, glue, position, notes) => ({ name, type: 'n8n-nodes-base.code', typeVersion: 2, position, notes, parameters: { mode: 'runOnceForAllItems', language: 'javaScript', jsCode: buildCode(glue) } });
const respondNode = (name, body, code, position) => ({
  name, type: 'n8n-nodes-base.respondToWebhook', typeVersion: 1.5, position,
  parameters: { respondWith: 'json', responseBody: body, options: { responseCode: code } }
});
const sticky = (name, content, position, width, height) => ({ name, type: 'n8n-nodes-base.stickyNote', typeVersion: 1, position, parameters: { content, width, height } });

// ------------------------------------------------------------------ workflow
function buildWorkflow(opts) {
  const o = Object.assign({ saveSuccess: 'none' }, opts || {});
  const nodes = [
    {
      name: 'Webhook de leads', type: 'n8n-nodes-base.webhook', typeVersion: 2.2, position: [0, 0],
      webhookId: uid('webhook-id'),
      parameters: { httpMethod: 'POST', path: 'leadflow-sales', authentication: 'headerAuth', responseMode: 'responseNode', options: {} },
      credentials: { httpHeaderAuth: { id: 'REPLACE_WITH_YOUR_CREDENTIAL', name: 'LeadFlow webhook token' } },
      notes: 'POST JSON. Requires the header configured in the "LeadFlow webhook token" credential.'
    },
    { name: 'Reintentar fallidos', type: 'n8n-nodes-base.manualTrigger', typeVersion: 1, position: [0, 560], parameters: {}, notes: 'Manual, bounded retry of failed or stuck leads (max ' + CONFIG.maxRetries + ' attempts each).' },
    {
      name: 'Configuración', type: 'n8n-nodes-base.set', typeVersion: 3.4, position: [260, 280],
      notes: 'The only place to paste the Google Sheet ID.',
      parameters: {
        mode: 'manual', includeOtherFields: true, options: {},
        assignments: { assignments: [
          { id: uid('cfg-sheet').slice(0, 18), name: 'sheet_id', value: 'PASTE_YOUR_GOOGLE_SHEET_ID_HERE', type: 'string' },
          { id: uid('cfg-mode').slice(0, 18), name: 'mode', value: '={{ $json.body !== undefined ? "webhook" : "retry" }}', type: 'string' }
        ] }
      }
    },
    ifNode('¿Envío web?', cond('={{ $json.mode }}', { type: 'string', operation: 'equals' }, 'webhook'), [520, 280]),
    codeNode('Validar y normalizar', 'validate-normalize.js', [780, 120], 'Validates required fields, cleans text, masks payment/ID numbers, flags injection and builds stable ids.'),
    ifNode('¿Lead válido?', cond('={{ $json.valid }}', { type: 'boolean', operation: 'true', singleValue: true }), [1040, 120]),
    respondNode('Responder error de validación', '={{ JSON.stringify({ ok: false, errors: $json.errors }) }}', 422, [1300, 0]),
    {
      name: 'Buscar historial del lead', type: 'n8n-nodes-base.googleSheets', typeVersion: 4.7, position: [1300, 240], alwaysOutputData: true,
      parameters: {
        resource: 'sheet', operation: 'read', documentId: docRef(), sheetName: tabRef('leads'),
        filtersUI: { values: [{ lookupColumn: 'lead_id', lookupValue: '={{ $("Validar y normalizar").first().json.lead.lead_id }}' }] },
        options: {}
      },
      credentials: SHEETS_CRED
    },
    codeNode('Decidir duplicado', 'decide-duplicate.js', [1560, 240], 'Exact submission match => ignore. Same email with a new message => process and flag contacto_repetido.'),
    ifNode('¿Procesar?', cond('={{ $json.action }}', { type: 'string', operation: 'equals' }, 'process'), [1820, 240]),
    respondNode('Responder duplicado', '={{ JSON.stringify($json.action === "conflict" ? { ok: false, error: "identifier_conflict" } : { ok: true, duplicate: true }) }}', '={{ $json.action === "conflict" ? 409 : 200 }}', [2080, 120]),
    upsertNode('Registrar recibido', 'leads', COLUMNS.leads, '$json.row', 'submission_id', [2080, 360], 'Writes the lead as "recibido" before calling the AI, so a crash leaves a visible, recoverable record.'),
    respondNode('Responder aceptado', '={{ JSON.stringify({ ok: true, status: "accepted", submission_id: $json.submission_id }) }}', 202, [2340, 240]),
    {
      name: 'Leer filas para reintento', type: 'n8n-nodes-base.googleSheets', typeVersion: 4.7, position: [780, 560],
      parameters: { resource: 'sheet', operation: 'read', documentId: docRef(), sheetName: tabRef('leads'), options: {} },
      credentials: SHEETS_CRED
    },
    codeNode('Preparar reintentos', 'prepare-retries.js', [1040, 560], 'Selects error_ia / error_validacion_ia rows and stuck "recibido" rows under the retry limit.'),
    codeNode('Preparar petición IA', 'prepare-ai-request.js', [2600, 360], 'Builds the request. Only the cleaned message is sent: no name, email, phone or company.'),
    {
      name: 'Analizar con IA', type: 'n8n-nodes-base.httpRequest', typeVersion: 4.5, position: [2860, 360],
      onError: 'continueRegularOutput', retryOnFail: true, maxTries: 3, waitBetweenTries: 2000,
      notes: 'Groq, OpenAI-compatible. 30 s timeout, 3 tries, then the lead is saved as error_ia.',
      parameters: {
        method: 'POST', url: CONFIG.ai.url,
        authentication: 'genericCredentialType', genericAuthType: 'httpHeaderAuth',
        sendBody: true, contentType: 'json', specifyBody: 'json', jsonBody: '={{ $json.ai_request }}',
        options: { timeout: 30000, batching: { batch: { batchSize: 1, batchInterval: 1500 } } }
      },
      credentials: { httpHeaderAuth: { id: 'REPLACE_WITH_YOUR_CREDENTIAL', name: 'Groq API key' } }
    },
    codeNode('Evaluar y puntuar', 'evaluate-score.js', [3120, 360], 'Validates the model answer, applies the explicit scoring rules and builds the lead row, the follow-up task and the error row.'),
    ifNode('¿Hay tarea?', cond('={{ $json.has_task }}', { type: 'boolean', operation: 'true', singleValue: true }), [3380, 360]),
    upsertNode('Guardar tarea', 'seguimiento', COLUMNS.seguimiento, '$json.task_row', 'task_id', [3640, 240], 'Follow-up task with a draft for human approval. Nothing is ever sent.'),
    upsertNode('Guardar lead', 'leads', COLUMNS.leads, '$("Evaluar y puntuar").item.json.lead_row', 'submission_id', [3900, 360], 'Final lead state, written after the task so a failed task write leaves the lead retryable.'),
    ifNode('¿Hay error?', cond('={{ $("Evaluar y puntuar").item.json.has_error }}', { type: 'boolean', operation: 'true', singleValue: true }), [4160, 360]),
    upsertNode('Registrar error', 'errores', COLUMNS.errores, '$("Evaluar y puntuar").item.json.error_row', 'error_id', [4420, 360], 'Bounded error log: e-mail addresses are masked.'),
    sticky('Nota: configuración',
      '## Setup (see docs/SETUP.md)\n1. Create the Google Sheet with the tabs `leads`, `seguimiento`, `errores` (CSV headers in `templates/`).\n2. Paste its ID in the **Configuración** node.\n3. Select your credentials: Google Sheets, Groq (Header Auth: `Authorization: Bearer <key>`) and the webhook token (Header Auth).\n4. Publish, then POST a lead.', [-40, -260], 520, 230),
    sticky('Nota: seguridad',
      '## Safety design\n- Lead text is untrusted data: cleaned, masked and wrapped in a tag; injection phrases are flagged.\n- The model only extracts signals and must quote evidence that exists in the message.\n- Priority comes from explicit rules in code, never from the model.\n- No node sends email. Follow-ups are tasks pending approval.', [1000, -260], 520, 230)
  ];

  const link = (from, to, outIndex, inIndex) => ({ from, to, out: outIndex || 0, in: inIndex || 0 });
  const links = [
    link('Webhook de leads', 'Configuración'),
    link('Reintentar fallidos', 'Configuración'),
    link('Configuración', '¿Envío web?'),
    link('¿Envío web?', 'Validar y normalizar', 0),
    link('¿Envío web?', 'Leer filas para reintento', 1),
    link('Validar y normalizar', '¿Lead válido?'),
    link('¿Lead válido?', 'Buscar historial del lead', 0),
    link('¿Lead válido?', 'Responder error de validación', 1),
    link('Buscar historial del lead', 'Decidir duplicado'),
    link('Decidir duplicado', '¿Procesar?'),
    link('¿Procesar?', 'Registrar recibido', 0),
    link('¿Procesar?', 'Responder duplicado', 1),
    link('Registrar recibido', 'Responder aceptado'),
    link('Registrar recibido', 'Preparar petición IA'),
    link('Leer filas para reintento', 'Preparar reintentos'),
    link('Preparar reintentos', 'Preparar petición IA'),
    link('Preparar petición IA', 'Analizar con IA'),
    link('Analizar con IA', 'Evaluar y puntuar'),
    link('Evaluar y puntuar', '¿Hay tarea?'),
    link('¿Hay tarea?', 'Guardar tarea', 0),
    link('¿Hay tarea?', 'Guardar lead', 1),
    link('Guardar tarea', 'Guardar lead'),
    link('Guardar lead', '¿Hay error?'),
    link('¿Hay error?', 'Registrar error', 0)
  ];
  const connections = {};
  links.forEach((l) => {
    connections[l.from] = connections[l.from] || { main: [] };
    const main = connections[l.from].main;
    while (main.length <= l.out) main.push([]);
    main[l.out].push({ node: l.to, type: 'main', index: l.in });
  });

  const outNodes = nodes.map((n) => {
    const node = {
      parameters: n.parameters,
      id: uid(n.name),
      name: n.name,
      type: n.type,
      typeVersion: n.typeVersion,
      position: n.position
    };
    if (n.webhookId) node.webhookId = n.webhookId;
    if (n.credentials) node.credentials = n.credentials;
    if (n.notes) { node.notes = n.notes; }
    ['onError', 'retryOnFail', 'maxTries', 'waitBetweenTries', 'alwaysOutputData'].forEach((k) => { if (n[k] !== undefined) node[k] = n[k]; });
    return node;
  });

  return {
    name: 'LeadFlow Sales AI',
    nodes: outNodes,
    pinData: {},
    connections,
    active: false,
    settings: { executionOrder: 'v1', saveDataSuccessExecution: o.saveSuccess, saveDataErrorExecution: 'all', saveManualExecutions: o.saveSuccess === 'all' },
    meta: { templateCredsSetupCompleted: false, version: CONFIG.version },
    tags: []
  };
}

function csvTemplates() {
  const out = {};
  Object.keys(COLUMNS).forEach((tab) => { out['templates/' + tab + '.csv'] = COLUMNS[tab].join(',') + '\n'; });
  return out;
}

function outputs() {
  const files = { 'workflows/leadflow-sales-ai.json': JSON.stringify(buildWorkflow(), null, 2) + '\n' };
  Object.assign(files, csvTemplates());
  return files;
}

module.exports = { buildWorkflow, buildCode, parseRegions, outputs, uid };

if (require.main === module) {
  const files = outputs();
  const check = process.argv.includes('--check');
  let stale = 0;
  Object.keys(files).forEach((rel) => {
    const abs = path.join(ROOT, rel);
    if (check) {
      const cur = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
      if (cur !== files[rel]) { console.error('OUT OF DATE: ' + rel); stale++; }
    } else {
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, files[rel]);
      console.log('wrote ' + rel + ' (' + files[rel].length + ' bytes)');
    }
  });
  if (check) { if (stale) process.exit(1); console.log('generated files are up to date'); }
}
